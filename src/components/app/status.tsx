import { cn } from "@/lib/utils";

type Tone = "neutral" | "info" | "success" | "warning" | "danger" | "brand" | "muted";

const TONE: Record<Tone, string> = {
  neutral: "bg-secondary text-secondary-foreground ring-foreground/10",
  info: "bg-info/10 text-info ring-info/20",
  success: "bg-success/10 text-success ring-success/20",
  warning: "bg-warning/10 text-warning ring-warning/25",
  danger: "bg-destructive/10 text-destructive ring-destructive/20",
  brand: "bg-primary/10 text-primary ring-primary/20",
  muted: "bg-muted text-muted-foreground ring-foreground/5",
};

export function Pill({ tone = "neutral", children, dot, className }: { tone?: Tone; children: React.ReactNode; dot?: boolean; className?: string }) {
  return (
    <span className={cn("inline-flex items-center gap-1.5 whitespace-nowrap rounded-full px-2 py-0.5 text-xs font-medium ring-1 ring-inset", TONE[tone], className)}>
      {dot && <span className="size-1.5 rounded-full bg-current" />}
      {children}
    </span>
  );
}

const CAMPAIGN: Record<string, { label: string; tone: Tone }> = {
  DRAFT: { label: "Draft", tone: "muted" },
  PENDING_APPROVAL: { label: "Pending approval", tone: "warning" },
  REJECTED: { label: "Rejected", tone: "danger" },
  APPROVED: { label: "Approved", tone: "info" },
  SCHEDULED: { label: "Scheduled", tone: "brand" },
  QUEUED: { label: "Queued", tone: "info" },
  RUNNING: { label: "Sending", tone: "info" },
  PAUSED: { label: "Paused", tone: "warning" },
  COMPLETED: { label: "Completed", tone: "success" },
  CANCELLED: { label: "Cancelled", tone: "muted" },
  FAILED: { label: "Failed", tone: "danger" },
};

export function CampaignStatusBadge({ status }: { status: string }) {
  const s = CAMPAIGN[status] ?? { label: status, tone: "neutral" as Tone };
  return (
    <Pill tone={s.tone} dot>
      {s.label}
    </Pill>
  );
}

const DELIVERY: Record<string, { label: string; tone: Tone }> = {
  PENDING: { label: "Pending", tone: "muted" },
  QUEUED: { label: "Queued", tone: "muted" },
  SUBMITTED: { label: "Submitted", tone: "info" },
  ACCEPTED: { label: "Provider accepted", tone: "info" },
  SENT: { label: "Sent", tone: "brand" },
  DELIVERED: { label: "Delivered", tone: "success" },
  READ: { label: "Read", tone: "success" },
  FAILED: { label: "Failed", tone: "danger" },
  BOUNCED: { label: "Bounced", tone: "danger" },
  CANCELLED: { label: "Cancelled", tone: "muted" },
  DRY_RUN: { label: "Dry run", tone: "neutral" },
};

export function DeliveryStatusBadge({ status, simulated }: { status: string; simulated?: boolean }) {
  const s = DELIVERY[status] ?? { label: status, tone: "neutral" as Tone };
  return (
    <span className="inline-flex items-center gap-1">
      <Pill tone={s.tone}>{s.label}</Pill>
      {simulated && <SimulatedTag />}
    </span>
  );
}

export function SimulatedTag() {
  return (
    <span title="Generated by the MOCK adapter — not real provider data" className="rounded border border-dashed border-warning/50 px-1 text-[10px] font-medium uppercase tracking-wide text-warning">
      sim
    </span>
  );
}

export function ModeBadge({ mode }: { mode: "MOCK" | "DRY_RUN" | "LIVE" | string }) {
  if (mode === "LIVE") return <Pill tone="danger" dot>Live</Pill>;
  if (mode === "DRY_RUN") return <Pill tone="info" dot>Dry run</Pill>;
  return <Pill tone="warning" dot>Mock</Pill>;
}

export function ChannelBadge({ channel }: { channel: string }) {
  if (channel === "BOTH")
    return (
      <span className="inline-flex gap-1">
        <ChannelBadge channel="EMAIL" />
        <ChannelBadge channel="WHATSAPP" />
      </span>
    );
  return <Pill tone={channel === "EMAIL" ? "brand" : "success"}>{channel === "EMAIL" ? "Email" : "WhatsApp"}</Pill>;
}

export function CategoryChip({ name, color, className }: { name: string; color: string; className?: string }) {
  return (
    <span className={cn("inline-flex max-w-[180px] items-center gap-1.5 truncate rounded-md border bg-surface px-1.5 py-0.5 text-xs", className)}>
      <span className="size-2 shrink-0 rounded-full" style={{ backgroundColor: color }} />
      <span className="truncate">{name}</span>
    </span>
  );
}
